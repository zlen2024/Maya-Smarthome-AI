#!/usr/bin/env python3
"""Rebuild the code2graph structural graph for the Maya repo.

Run from anywhere:  python wiki/graph/build_graph.py

Emits, next to this script:
  graph.json        full structural facts (symbols + edges), gitignored
  symbol_index.md   human-browsable catalog, committed

Two graphs are built because the right resolution tier differs by language:
  * Python server -> tier "scope"  (precise, resolves cleanly)
  * Dart mobile   -> tier "name"   ("scope" returns ZERO edges for Dart)
See wiki/pages/known-gaps.md before changing these.
"""
import json
import pathlib
import sys

import code2graph as c2g

REPO = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent

# Curated source roots. Never rglob the repo root: it would walk
# android/build output, .dart_tool, .venv and the Flutter pub cache.
ROOTS = [
    # (label, path relative to repo, extensions, resolution tier)
    ("server", "software/server", {".py"}, "scope"),
    ("mobile", "software/mobile/lib", {".dart"}, "name"),
]

EXCLUDE_DIRS = {
    "node_modules", "build", ".dart_tool", ".venv", "venv", "__pycache__",
    ".git", ".gradle", ".gradle_home", "android", "ios", "web", "windows",
    "linux", "macos", "Pods", "dist", ".idea",
}


def collect(root: pathlib.Path, exts: set[str]) -> dict[str, str]:
    files = {}
    for p in root.rglob("*"):
        if not p.is_file() or p.suffix not in exts:
            continue
        if any(part in EXCLUDE_DIRS for part in p.relative_to(root).parts):
            continue
        try:
            files[str(p.relative_to(REPO)).replace("\\", "/")] = p.read_text(
                encoding="utf-8", errors="replace"
            )
        except OSError as e:
            print(f"  !! unreadable {p}: {e}", file=sys.stderr)
    return files


def main() -> int:
    combined = {"roots": {}}
    catalog: list[str] = [
        "# Symbol Index",
        "",
        "Generated by `wiki/graph/build_graph.py` — **do not hand-edit**.",
        "Regenerate after code changes, then reconcile `wiki/pages/*.md` against it.",
        "",
    ]

    for label, rel, exts, tier in ROOTS:
        root = REPO / rel
        if not root.is_dir():
            print(f"skip {label}: {root} missing", file=sys.stderr)
            continue
        files = collect(root, exts)
        extracted = [c2g.extract(path, src) for path, src in sorted(files.items())]
        graph = c2g.build_graph(extracted, tier=tier)  # tier set EXPLICITLY
        combined["roots"][label] = {
            "path": rel,
            "tier": tier,
            "files": len(files),
            "graph": graph,
        }
        print(f"{label:8s} tier={tier:5s} files={len(files):3d} "
              f"symbols={len(graph.get('symbols', [])):4d} "
              f"edges={len(graph.get('edges', []))}")

        catalog += [f"## {label} — `{rel}` (tier `{tier}`)", ""]
        by_file: dict[str, list[dict]] = {}
        for sym in graph.get("symbols", []):
            by_file.setdefault(sym.get("file", "?"), []).append(sym)
        for fname in sorted(by_file):
            catalog.append(f"### `{fname}`")
            catalog.append("")
            for sym in sorted(by_file[fname], key=lambda s: s.get("line") or 0):
                kind = sym.get("kind", "?")
                name = sym.get("name", "?")
                line = sym.get("line", "?")
                catalog.append(f"- `{kind}` **{name}** — L{line}")
            catalog.append("")

    (OUT / "graph.json").write_text(
        json.dumps(combined, indent=1), encoding="utf-8"
    )
    (OUT / "symbol_index.md").write_text("\n".join(catalog) + "\n", encoding="utf-8")
    print(f"wrote {OUT/'graph.json'} and {OUT/'symbol_index.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
