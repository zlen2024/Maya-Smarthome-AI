"""Generate index.html from tools/timing.json — the assembly step, repeatable after any retime.

Run from the project root: python tools/build_index.py

Scene slots overlap by the timing file's OVERLAP (each incoming scene fades in over the outgoing one,
inside its own composition). Narration clips are placed at their global times and share one
`voiceover` audio group, which the music bed is carved against. The demo clip's own soundtrack joins
that group so the bed ducks under it too.
"""
import io
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BGM = "assets/bgm/track-226s.mp3"
BGM_VOLUME = 0.14
BGM_FADE_IN = 1.5
BGM_FADE_OUT = 2.5

HEAD = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>MAYA · Hackathon pitch (CBN8426079)</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * {
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }
      html,
      body {
        margin: 0;
        width: 1920px;
        height: 1080px;
        overflow: hidden;
        background: #E5E4E2;
      }
      #root {
        position: relative;
        width: 100%;
        height: 100%;
        overflow: hidden;
        background: #E5E4E2;
      }
      [data-composition-id="main"] > div[data-composition-src] {
        position: absolute;
        inset: 0;
      }
    </style>
  </head>
  <body>
    <!--
      GENERATED by tools/build_index.py from tools/timing.json — do not hand-edit the clip times.
      Re-run tools/cues.py then tools/build_index.py after any voice or scene change.
    -->
"""

TAIL = """    </div>
    <script>
      (function () {
        var tl = gsap.timeline({ paused: true });
        var bgm = document.getElementById("bgm");
        tl.fromTo(bgm, { volume: 0 }, { volume: __VOL__, duration: __FIN__, ease: "none" }, 0);
        tl.fromTo(bgm, { volume: __VOL__ }, { volume: 0, duration: __FOUT__, ease: "none", immediateRender: false }, __FOUT_AT__);
        window.__timelines["main"] = tl;
      })();
    </script>
  </body>
</html>
"""

SEGMENT_LABEL = {"01-hook": "Introduction", "03-problem": "Contents", "16-close": "Conclusion"}


def main():
    t = json.load(open(os.path.join(ROOT, "tools", "timing.json"), encoding="utf-8"))
    total = t["total_seconds"]
    out = [HEAD]
    out.append(f'    <div id="root" data-composition-id="main" data-start="0" data-duration="{total}" '
               f'data-width="1920" data-height="1080">\n')

    for i, f in enumerate(t["frames"]):
        slug = f["slug"]
        if slug in SEGMENT_LABEL:
            out.append(f"      <!-- {SEGMENT_LABEL[slug]} -->\n")
        out.append(f'      <div id="el-{slug}" data-composition-id="f{slug}" '
                   f'data-composition-src="compositions/frames/{slug}.html" data-start="{f["start"]}" '
                   f'data-duration="{f["duration"]}" data-track-index="{1 + i % 2}" '
                   f'data-width="1920" data-height="1080"></div>\n')

    out.append('\n      <!-- Narration: Gemini TTS — Puck and Sulafat — plus the demo clip\'s own soundtrack -->\n')
    for f in t["frames"]:
        for l in f["lines"]:
            start = round(f["start"] + l["local_start"], 3)
            track = 10 if l["voice"] == "Puck" else 11
            out.append(f'      <audio id="vo-{l["id"]}" src="{l["path"]}" data-audio-group="voiceover" '
                       f'data-start="{start}" data-duration="{l["seconds"]}" data-track-index="{track}" '
                       f'data-volume="1"></audio>\n')
        if f.get("media"):
            start = round(f["start"] + f["media_start"], 3)
            dur = round(f["duration"] - f["media_start"] - 0.5, 2)
            out.append(f'      <audio id="vo-{f["slug"]}-clip" src="{f["media"]}" data-audio-group="voiceover" '
                       f'data-start="{start}" data-duration="{dur}" data-track-index="12" '
                       f'data-volume="0.95"></audio>\n')

    out.append(f'\n      <!-- Music bed: Google Lyria, extended to 185s; carved under the voiceover group -->\n'
               f'      <audio id="bgm" src="{BGM}" data-start="0" data-duration="{total}" '
               f'data-track-index="20" data-volume="{BGM_VOLUME}"></audio>\n')

    tail = (TAIL.replace("__VOL__", str(BGM_VOLUME)).replace("__FIN__", str(BGM_FADE_IN))
            .replace("__FOUT__", str(BGM_FADE_OUT)).replace("__FOUT_AT__", str(round(total - BGM_FADE_OUT, 2))))
    out.append(tail)

    path = os.path.join(ROOT, "index.html")
    io.open(path, "w", encoding="utf-8", newline="\n").write("".join(out))
    scenes = len(t["frames"])
    clips = sum(len(f["lines"]) for f in t["frames"]) + sum(1 for f in t["frames"] if f.get("media"))
    print(f"index.html written: {scenes} scenes, {clips} narration/media clips + bgm, total {total:.2f}s "
          f"({int(total // 60)}:{total % 60:04.1f})")
    print("NOTE: re-run the carve after this (node ../../.claude/skills/hyperframes-audio/scripts/carve.mjs --comp index.html)")


if __name__ == "__main__":
    main()
